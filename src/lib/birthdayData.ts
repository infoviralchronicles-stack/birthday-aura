export function getZodiacSign(month: number, day: number): string {
  if ((month === 3 && day >= 21) || (month === 4 && day <= 19)) return 'Aries';
  if ((month === 4 && day >= 20) || (month === 5 && day <= 20)) return 'Taurus';
  if ((month === 5 && day >= 21) || (month === 6 && day <= 20)) return 'Gemini';
  if ((month === 6 && day >= 21) || (month === 7 && day <= 22)) return 'Cancer';
  if ((month === 7 && day >= 23) || (month === 8 && day <= 22)) return 'Leo';
  if ((month === 8 && day >= 23) || (month === 9 && day <= 22)) return 'Virgo';
  if ((month === 9 && day >= 23) || (month === 10 && day <= 22)) return 'Libra';
  if ((month === 10 && day >= 23) || (month === 11 && day <= 21)) return 'Scorpio';
  if ((month === 11 && day >= 22) || (month === 12 && day <= 21)) return 'Sagittarius';
  if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) return 'Capricorn';
  if ((month === 1 && day >= 20) || (month === 2 && day <= 18)) return 'Aquarius';
  return 'Pisces';
}

export function getTodayDateKey(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Calculates a dynamic daily popularity score for a celebrity on a given date,
 * combining base popularity, daily trending momentum (rotates every 24h),
 * birthday-month/week proximity surge, and live user clicks/boosts today.
 */
export function getDailyPopularityScore(
  star: CelebrityProfile,
  date: Date = new Date(),
  liveDailyHits: number = 0
): number {
  const dateKey = getTodayDateKey(date);
  const seedStr = `${dateKey}::${star.id}`;
  let hash = 2166136261;
  for (let i = 0; i < seedStr.length; i++) {
    hash ^= seedStr.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const dailySurge = (hash >>> 0) % 95000;
  const currentMonth = date.getMonth() + 1;
  const monthBonus = star.birthMonth === currentMonth ? 18000 : 0;
  return star.boosts * 0.55 + dailySurge + monthBonus + liveDailyHits * 25000;
}

